create table wishes (
    id bigint generated by default as identity primary key,
    member_id bigint not null references members(id),
    product_id bigint not null,
    constraint uq_wishes_member_product unique (member_id, product_id),
    constraint fk_wishes_product foreign key (product_id) references products(id) on delete cascade
);

create index idx_wishes_product on wishes(product_id);
